package org.perlonjava.runtime.regex;

import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.Base64;

public final class PerlUnicodeScalarNameData {
HEADER
print "    public static final String SOURCE_SHA256 = \"$source_sha256\";\n";
print "    public static final int ENTRY_COUNT = ", scalar(@names), ";\n";
print "    public static final int DUPLICATE_NAME_COUNT = ", scalar(@duplicate_names), ";\n\n";
print "    private static final String[] ENCODED = {\n";
print qq{        "$_",\n} for @chunks;
print <<'FOOTER';
    };

    private static final String[] NAMES;
    private static final int[] CODE_POINTS;

    static {
        byte[] data = Base64.getDecoder().decode(String.join("", ENCODED));
        Cursor cursor = new Cursor();
        int count = readVarint(data, cursor);
        if (count != ENTRY_COUNT) {
            throw new IllegalStateException("Invalid generated Perl scalar-name count: " + count);
        }
        NAMES = new String[count];
        CODE_POINTS = new int[count];
        String previous = "";
        for (int index = 0; index < count; index++) {
            int prefixLength = readVarint(data, cursor);
            int suffixLength = readVarint(data, cursor);
            int codePoint = readVarint(data, cursor);
            if (prefixLength > previous.length()
                    || suffixLength > data.length - cursor.offset) {
                throw new IllegalStateException("Invalid generated Perl scalar-name data");
            }
            String suffix = new String(
                    data, cursor.offset, suffixLength, StandardCharsets.US_ASCII);
            cursor.offset += suffixLength;
            String name = previous.substring(0, prefixLength) + suffix;
            NAMES[index] = name;
            CODE_POINTS[index] = codePoint;
            previous = name;
        }
        if (cursor.offset != data.length) {
            throw new IllegalStateException("Trailing generated Perl scalar-name data");
        }
    }

    public static int codePoint(String name) {
        if (name == null) return -1;
        int index = Arrays.binarySearch(NAMES, name);
        return index < 0 ? -1 : CODE_POINTS[index];
    }

    static int entryCount() {
        return NAMES.length;
    }

    private static int readVarint(byte[] data, Cursor cursor) {
        int value = 0;
        int shift = 0;
        while (cursor.offset < data.length && shift < 35) {
            int current = data[cursor.offset++] & 0xff;
            value |= (current & 0x7f) << shift;
            if ((current & 0x80) == 0) return value;
            shift += 7;
        }
        throw new IllegalStateException("Invalid generated Perl scalar-name varint");
    }

    private static final class Cursor {
        private int offset;
    }

    private PerlUnicodeScalarNameData() {
    }
}
FOOTER

sub common_prefix_length {
    my ($left, $right) = @_;
    my $limit = length($left) < length($right) ? length($left) : length($right);
    my $offset = 0;
    $offset++ while $offset < $limit
            && substr($left, $offset, 1) eq substr($right, $offset, 1);
    return $offset;
}

sub encode_varint {
    my ($value) = @_;
    my $encoded = '';
    while ($value >= 0x80) {
        $encoded .= chr(($value & 0x7f) | 0x80);
        $value >>= 7;
    }
    return $encoded . chr($value);
}
