my $repo_root = File::Spec->rel2abs(File::Spec->catdir($FindBin::Bin, '..', '..', '..'));
my $source = $ENV{PERLONJAVA_NAME_PL}
        // File::Spec->catfile($repo_root, 'src', 'main', 'perl', 'lib', 'unicore', 'Name.pl');
open my $source_fh, '<:raw', $source or die "Cannot read $source: $!\n";
local $/;
my $source_text = <$source_fh>;
close $source_fh or die "Cannot close $source: $!\n";
my $source_sha256 = sha256_hex($source_text);
$source_text =~ /return <<'END';\r?\n(.*)\r?\nEND\r?\n?\z/s
        or die "$source does not have the expected generated Name.pl format\n";
my $records = $1;
$records =~ s/\r\n/\n/g;

my (%first_code_point, @duplicate_names);
for my $record (split /\n\n/, $records) {
    my ($code_points, $name, @extra) = split /\n/, $record;
    die "Malformed Name.pl record: $record\n"
            if !defined $name || @extra || !length $name;
    next if $code_points =~ /\s/; # Multi-code-point sequences have a separate owner.
    die "Invalid scalar code point '$code_points' for '$name'\n"
            unless $code_points =~ /\A[0-9A-F]{5,6}\z/;
    die "Non-ASCII or tab character in scalar name '$name'\n"
            unless $name =~ /\A[\x20-\x7E]+\z/ && $name !~ /\t/;
    if (exists $first_code_point{$name}) {
        push @duplicate_names, $name;
        next; # Match Name.pl's anchored search: the first name row wins.
    }
    $first_code_point{$name} = hex $code_points;
}

my @names = sort keys %first_code_point;
die "Name.pl contains no scalar names\n" unless @names;
my $binary = encode_varint(scalar @names);
my $previous = '';
for my $name (@names) {
    my $prefix_length = common_prefix_length($previous, $name);
    my $suffix = substr($name, $prefix_length);
    $binary .= encode_varint($prefix_length)
            . encode_varint(length $suffix)
            . encode_varint($first_code_point{$name})
            . encode('ASCII', $suffix);
    $previous = $name;
}
my $encoded = encode_base64($binary, '');
my @chunks = $encoded =~ /.{1,8000}/g;

print <<'HEADER';
